--creacion de tablas 
CREATE TABLE REGION (
    cod_region NUMBER NOT NULL,
    nombre     VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (cod_region),
    CONSTRAINT REGION_nombre_UN UNIQUE (nombre)
);

CREATE SEQUENCE SEQ_REGION
    START WITH 21
    INCREMENT BY 1;

CREATE TABLE COMUNA (
    cod_comuna        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1050 INCREMENT BY 5),
    nombre            VARCHAR2(100) NOT NULL,
    REGION_cod_region NUMBER,
    CONSTRAINT PK_COMUNA PRIMARY KEY (cod_comuna),
    CONSTRAINT COMUNA_nombre_UN UNIQUE (nombre),
    CONSTRAINT FK_COMUNA_REGION FOREIGN KEY (REGION_cod_region)
        REFERENCES REGION (cod_region)
);


CREATE TABLE PLANTA (
    cod_planta        NUMBER NOT NULL,
    nombre            VARCHAR2(100) NOT NULL,
    direccion         VARCHAR2(200) NOT NULL,
    COMUNA_cod_comuna NUMBER,
    CONSTRAINT PK_PLANTA PRIMARY KEY (cod_planta),
    CONSTRAINT PLANTA_nombre_UN UNIQUE (nombre),
    CONSTRAINT FK_PLANTA_COMUNA FOREIGN KEY (COMUNA_cod_comuna)
        REFERENCES COMUNA (cod_comuna)
);

CREATE TABLE AFP (
    id_afp NUMBER NOT NULL,
    nombre VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_AFP PRIMARY KEY (id_afp),
    CONSTRAINT AFP_nombre_UN UNIQUE (nombre)
);

CREATE TABLE SALUD (
    id_salud NUMBER NOT NULL,
    nombre   VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_SALUD PRIMARY KEY (id_salud),
    CONSTRAINT SALUD_nombre_UN UNIQUE (nombre)
);

CREATE TABLE ESTADO_ACTIVO (
    id_estado   NUMBER NOT NULL,
    tipo_estado CHAR(2) NOT NULL,
    CONSTRAINT PK_ESTADO_ACTIVO PRIMARY KEY (id_estado),
    CONSTRAINT ESTADO_ACTIVO_tipo_estado_UN UNIQUE (tipo_estado)
);

CREATE TABLE ESTADO_MAQUI (
    id_estado   NUMBER NOT NULL,
    tipo_estado CHAR(1) NOT NULL,
    CONSTRAINT PK_ESTADO_MAQUI PRIMARY KEY (id_estado),
    CONSTRAINT ESTADO_MAQUI_tipo_estado_UN UNIQUE (tipo_estado)
);

CREATE TABLE CATEGORIA (
    id_categoria NUMBER NOT NULL,
    nombre       VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (id_categoria),
    CONSTRAINT CATEGORIA_nombre_UN UNIQUE (nombre)
);

CREATE TABLE CERTIFICACION (
    id_certificacion NUMBER NOT NULL,
    presencia        VARCHAR2(2) NOT NULL,
    CONSTRAINT PK_CERTIFICACION PRIMARY KEY (id_certificacion)
);

CREATE TABLE ESPECIALIDAD (
    id_especialidad NUMBER NOT NULL,
    nombre_e        VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_ESPECIALIDAD PRIMARY KEY (id_especialidad),
    CONSTRAINT ESPECIALIDAD_nombre_e_UN UNIQUE (nombre_e)
);


CREATE TABLE MAQUINA (
    id_maquina   NUMBER NOT NULL,
    numero       NUMBER NOT NULL,
    tipo_maquina VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_MAQUINA PRIMARY KEY (id_maquina),
    CONSTRAINT CK_MAQUINA_NUM CHECK (numero > 0)
);

CREATE TABLE ESTADO_MAQUIv2 (
    ESTADO_MAQUI_id_estado NUMBER NOT NULL,
    MAQUINA_id_maquina     NUMBER NOT NULL,
    CONSTRAINT PK_ESTADO_MAQUIv2 PRIMARY KEY (ESTADO_MAQUI_id_estado, MAQUINA_id_maquina),
    CONSTRAINT FK_ESTADO_MAQUIv2_ESTADO FOREIGN KEY (ESTADO_MAQUI_id_estado)
        REFERENCES ESTADO_MAQUI (id_estado),
    CONSTRAINT FK_ESTADO_MAQUIv2_MAQUINA FOREIGN KEY (MAQUINA_id_maquina)
        REFERENCES MAQUINA (id_maquina)
);

CREATE TABLE TURNO (
    id_turno    NUMBER NOT NULL,
    hora_inicio CHAR(5) NOT NULL,
    hora_fin    CHAR(5) NOT NULL,
    fecha       DATE NOT NULL,
    CONSTRAINT PK_TURNO PRIMARY KEY (id_turno)
);

CREATE TABLE TIPO_TURNO (
    id_tipo NUMBER NOT NULL,
    tipo    VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_TIPO_TURNO PRIMARY KEY (id_tipo),
    CONSTRAINT TIPO_TURNO_tipo_UN UNIQUE (tipo)
);

CREATE TABLE INTERMEDIA_TURNO (
    TURNO_id_turno     NUMBER NOT NULL,
    TIPO_TURNO_id_tipo NUMBER NOT NULL,
    CONSTRAINT PK_INTERMEDIA_TURNO PRIMARY KEY (TURNO_id_turno, TIPO_TURNO_id_tipo),
    CONSTRAINT FK_INTERMEDIA_TURNO_TURNO FOREIGN KEY (TURNO_id_turno)
        REFERENCES TURNO (id_turno),
    CONSTRAINT FK_INTERMEDIA_TURNO_TIPO FOREIGN KEY (TIPO_TURNO_id_tipo)
        REFERENCES TIPO_TURNO (id_tipo)
);

