SELECT 
    tt.tipo AS TURNO,
    t.hora_inicio AS ENTRADA,
    t.hora_fin AS SALIDA
FROM 
    TURNO t
    JOIN INTERMEDIA_TURNO it ON t.id_turno = it.TURNO_id_turno
    JOIN TIPO_TURNO tt ON it.TIPO_TURNO_id_tipo = tt.id_tipo
WHERE 
    TO_NUMBER(SUBSTR(t.hora_inicio, 1, 2)) > 20
ORDER BY 
    t.hora_inicio DESC;


